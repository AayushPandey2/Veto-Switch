"""Deterministic offline FixtureLLMProvider for testing, demos, and offline evaluations.

All responses emitted by ``FixtureLLMProvider`` set ``synthetic_origin=True`` and
``provider="offline_fixture"`` and must NEVER be presented as live LLM quality.
"""

from __future__ import annotations

import json
import uuid
from collections import deque
from collections.abc import Callable
from enum import StrEnum
from typing import Any

from shared.enums import AIProviderErrorCategory, ClaimCategory, VulnerabilityCategory
from shared.identifiers import utc_now

from agent_core.llm.error_mapping import NormalizedLLMError
from agent_core.llm.provider import GatewayLLMProvider, ProviderCapabilities
from agent_core.llm.request import GatewayLLMRequest
from agent_core.llm.response import GatewayLLMResponse, ToolCallRequest


class FixtureBehaviorMode(StrEnum):
    """Scripted deterministic behaviors supported by ``FixtureLLMProvider``."""

    VALID = "valid"
    MALFORMED_JSON = "malformed_json"
    SCHEMA_INVALID = "schema_invalid"
    UNEXPECTED_FIELDS = "unexpected_fields"
    TIMEOUT = "timeout"
    RATE_LIMIT = "rate_limit"
    UNAVAILABLE = "unavailable"
    AUTH_ERROR = "auth_error"
    INVALID_MODEL = "invalid_model"
    CONTENT_RESTRICTION = "content_restriction"
    UNSUPPORTED_TOOL = "unsupported_tool"
    FORBIDDEN_TOOL_REQUEST = "forbidden_tool_request"
    HALLUCINATED_EVIDENCE = "hallucinated_evidence"
    CONTRADICTORY_CLAIM = "contradictory_claim"
    REPRODUCED_OVERCLAIM = "reproduced_overclaim"
    CVE_EXPLOITED_OVERCLAIM = "cve_exploited_overclaim"
    DEPLOYED_WITHOUT_EVIDENCE = "deployed_without_evidence"
    MISSING_USAGE = "missing_usage"


FixtureResponseFn = Callable[[GatewayLLMRequest], dict[str, Any]]


def _extract_fixture_facts(request: GatewayLLMRequest) -> dict[str, Any]:
    ctx = request.structured_context
    finding = ctx.get("finding", {}) if isinstance(ctx.get("finding"), dict) else {}
    ver = (
        ctx.get("verification_summary", {})
        if isinstance(ctx.get("verification_summary"), dict)
        else {}
    )
    ev_refs = ctx.get("evidence_references", [])
    ev_ids: list[str] = [
        str(e["artifact_id"])
        for e in ev_refs
        if isinstance(e, dict) and e.get("artifact_id")
    ]

    excerpts = ctx.get("bounded_source_excerpts", [])
    source_ids = [
        str(s["file_id"]) for s in excerpts if isinstance(s, dict) and s.get("file_id")
    ]
    return {
        "incident_id": request.incident_id or finding.get("incident_id", "inc_unknown"),
        "finding_id": finding.get("finding_id", "fnd_unknown"),
        "category": finding.get("category", VulnerabilityCategory.OTHER.value),
        "status": finding.get("status", "suspected"),
        "component": finding.get("affected_component", "unknown_component"),
        "route": finding.get("affected_route"),
        "environment": ctx.get("environment") or finding.get("environment") or "staging",
        "revision": ctx.get("repository_revision") or finding.get("repository_revision"),
        "outcome": ver.get("reproduction_outcome", "not_run"),
        "conflicting": bool(ver.get("conflicting_outcomes", False)),
        "missing_info": list(ctx.get("missing_information", [])),
        "limitations": list(ctx.get("known_limitations", [])),
        "evidence_ids": ev_ids,
        "source_ids": source_ids,
        "has_source": bool(source_ids),
    }


def _build_valid_investigation_payload(request: GatewayLLMRequest) -> dict[str, Any]:
    facts = _extract_fixture_facts(request)
    ev_ids = facts["evidence_ids"]
    status = facts["status"]
    category = facts["category"]
    component = facts["component"]
    route = facts["route"]
    has_source = facts["has_source"]
    outcome = facts["outcome"]

    primary_ev = ev_ids[:1]
    ver_ev = [e for e in ev_ids if "repro" in e or "ver" in e][:1] or primary_ev

    verified_claims: list[dict[str, Any]] = []
    if primary_ev:
        verified_claims.append(
            {
                "claim_id": "clm_0001",
                "statement": (
                    f"[SYNTHETIC FIXTURE] Normalized {category} finding {facts['finding_id']} "
                    f"targets component {component!r} with authoritative status={status!r}."
                ),
                "classification": ClaimCategory.OBSERVED.value,
                "evidence_ids": primary_ev,
                "source_excerpt_ids": [],
                "environment": facts["environment"],
                "source_revision": facts["revision"],
                "limitations": ["Generated by deterministic synthetic fixture provider."],
            }
        )
    if outcome == "reproduced" and ver_ev:
        verified_claims.append(
            {
                "claim_id": "clm_0002",
                "statement": (
                    f"[SYNTHETIC FIXTURE] Authorized security verification outcome is "
                    f"reproduced ({outcome!r}) in environment {facts['environment']!r}."
                ),
                "classification": ClaimCategory.OBSERVED.value,
                "evidence_ids": ver_ev,
                "source_excerpt_ids": [],
                "environment": facts["environment"],
                "source_revision": facts["revision"],
                "limitations": [],
            }
        )

    interpretations: list[dict[str, Any]] = []
    if has_source and ev_ids:
        interpretations.append(
            {
                "claim_id": "clm_0003",
                "statement": (
                    f"[SYNTHETIC FIXTURE] Bounded source excerpt for {component!r} exhibits "
                    f"patterns consistent with {category}."
                ),
                "classification": ClaimCategory.INFERRED.value,
                "evidence_ids": ev_ids[:2],
                "source_excerpt_ids": facts["source_ids"][:1],
                "environment": facts["environment"],
                "source_revision": facts["revision"],
                "limitations": ["Technical interpretation synthesized from supplied fixture data."],
            }
        )

    uncertainties: list[str] = []
    missing_evidence: list[str] = []
    if not has_source:
        missing_evidence.append("authorized_source_excerpt")
        uncertainties.append(
            "Exact source-level root cause statement is unavailable without excerpt."
        )
    if status != "reproduced" or outcome != "reproduced":
        missing_evidence.append("confirmed_reproduction_verification")
        uncertainties.append("Exploitability has not been established by trusted reproduction.")
    if category == VulnerabilityCategory.DEPENDENCY_CVE.value:
        uncertainties.append(
            "Dependency advisory match alone does not confirm runtime reachability or exploitation."
        )

    has_mismatch_limitations = any(
        "mismatch" in lim.lower() for lim in facts["limitations"]
    )
    if (
        category == VulnerabilityCategory.OTHER.value
        or facts["conflicting"]
        or has_mismatch_limitations
    ):
        next_action = "require_manual_review"
    elif status == "reproduced" and outcome == "reproduced" and ev_ids:
        next_action = "request_feature_mapping"
    elif status == "suspected":
        next_action = "request_verification"
    else:
        next_action = "request_more_evidence"

    return {
        "executive_summary": (
            f"[SYNTHETIC FIXTURE] {category} investigation for {component}"
            + (f" ({route})" if route else "")
            + f" [status={status}]."
        ),
        "technical_explanation": (
            f"[SYNTHETIC FIXTURE] Analyzed {category} finding for {component!r} using "
            f"{len(ev_ids)} supplied evidence artifact(s) and "
            f"{len(facts['source_ids'])} bounded source excerpt(s)."
        ),
        "affected_components": [component],
        "observed_effects": (
            [f"Observed verification outcome={outcome!r} for {route or component}."]
            if outcome == "reproduced"
            else []
        ),
        "grounded_facts": verified_claims,
        "technical_interpretations": interpretations,
        "potential_impacts": [
            {
                "description": (
                    f"Potential {category} exposure in {component!r} if vulnerable code path "
                    "is reachable."
                ),
                "verified": bool(status == "reproduced" and outcome == "reproduced"),
                "limitations": [
                    "Broader system impact beyond supplied evidence has not been tested."
                ],
            }
        ],
        "assumptions": (
            ["Assumes dependency version metadata reflects runtime environment."]
            if category == VulnerabilityCategory.DEPENDENCY_CVE.value
            else []
        ),
        "uncertainties": uncertainties or ["Scope limited to supplied bounded artifacts."],
        "missing_evidence": missing_evidence,
        "recommended_next_action": next_action,
        "evidence_ids": ev_ids,
        "model_reported_confidence": "limited_evidence_support",
    }


class FixtureLLMProvider(GatewayLLMProvider):
    """Deterministic scripted provider for offline testing and simulations."""

    provider_name: str = "offline_fixture"

    def __init__(
        self,
        *,
        default_mode: FixtureBehaviorMode = FixtureBehaviorMode.VALID,
        mode_sequence: list[FixtureBehaviorMode] | None = None,
        custom_payload_fn: FixtureResponseFn | None = None,
        supports_native_schema: bool = True,
        supports_tool_calling: bool = True,
        supports_token_counting: bool = True,
    ) -> None:
        self.default_mode = default_mode
        self._mode_queue: deque[FixtureBehaviorMode] = deque(mode_sequence or [])
        self._custom_payload_fn = custom_payload_fn
        self._capabilities = ProviderCapabilities(
            supports_structured_json=True,
            supports_native_schema=supports_native_schema,
            supports_tool_calling=supports_tool_calling,
            supports_token_counting=supports_token_counting,
            supports_temperature=True,
            max_context_tokens=32_000,
            max_output_tokens=4096,
            supported_parameters=("temperature", "max_output_tokens", "response_schema"),
            is_synthetic_fixture=True,
        )
        self.invocations: list[dict[str, Any]] = []

    def enqueue_mode(self, mode: FixtureBehaviorMode) -> None:
        """Append a scripted response mode for the next provider invocation."""
        self._mode_queue.append(mode)

    def get_capabilities(self) -> ProviderCapabilities:
        return self._capabilities

    async def count_tokens(self, text: str, *, model_name: str) -> int | None:
        if not self._capabilities.supports_token_counting:
            return None
        return max(1, (len(text) + 3) // 4)

    async def generate(self, request: GatewayLLMRequest) -> GatewayLLMResponse:
        mode = self._mode_queue.popleft() if self._mode_queue else self.default_mode
        self.invocations.append(
            {
                "request_id": request.request_id,
                "incident_id": request.incident_id,
                "task_type": request.task_type.value,
                "model_name": request.model_name,
                "prompt_version": request.prompt_version,
                "context_hash": request.context_hash,
                "mode": mode.value,
            }
        )

        if mode == FixtureBehaviorMode.TIMEOUT:
            raise NormalizedLLMError(
                "Simulated offline fixture timeout.",
                category=AIProviderErrorCategory.TIMEOUT,
                provider=self.provider_name,
                status_code=504,
            )
        if mode == FixtureBehaviorMode.RATE_LIMIT:
            raise NormalizedLLMError(
                "Simulated offline fixture rate limit.",
                category=AIProviderErrorCategory.RATE_LIMIT,
                provider=self.provider_name,
                status_code=429,
                retry_after_seconds=0.01,
            )
        if mode == FixtureBehaviorMode.UNAVAILABLE:
            raise NormalizedLLMError(
                "Simulated offline fixture temporary unavailability.",
                category=AIProviderErrorCategory.TEMPORARY_UNAVAILABLE,
                provider=self.provider_name,
                status_code=503,
            )
        if mode == FixtureBehaviorMode.AUTH_ERROR:
            raise NormalizedLLMError(
                "Simulated authentication failure.",
                category=AIProviderErrorCategory.AUTHENTICATION_ERROR,
                provider=self.provider_name,
                status_code=401,
            )
        if mode == FixtureBehaviorMode.INVALID_MODEL:
            raise NormalizedLLMError(
                f"Simulated invalid model configuration {request.model_name!r}.",
                category=AIProviderErrorCategory.INVALID_MODEL_CONFIGURATION,
                provider=self.provider_name,
                status_code=404,
            )
        if mode == FixtureBehaviorMode.CONTENT_RESTRICTION:
            raise NormalizedLLMError(
                "Simulated provider content restriction block.",
                category=AIProviderErrorCategory.CONTENT_RESTRICTION,
                provider=self.provider_name,
                status_code=400,
            )

        if mode == FixtureBehaviorMode.MALFORMED_JSON:
            return GatewayLLMResponse(
                request_id=request.request_id,
                provider=self.provider_name,
                model=request.model_name,
                provider_response_id=f"fix_{uuid.uuid4().hex[:12]}",
                content="{not valid json: [unclosed",
                structured_response=None,
                finish_reason="stop",
                input_tokens=120,
                output_tokens=12,
                total_tokens=132,
                latency_ms=1.0,
                timestamp=utc_now(),
                status="ok",
                synthetic_origin=True,
            )

        if mode == FixtureBehaviorMode.SCHEMA_INVALID:
            bad = {"executive_summary": ""}  # Missing required fields + invalid empty summary
            return GatewayLLMResponse(
                request_id=request.request_id,
                provider=self.provider_name,
                model=request.model_name,
                provider_response_id=f"fix_{uuid.uuid4().hex[:12]}",
                content=json.dumps(bad),
                structured_response=bad,
                finish_reason="stop",
                input_tokens=100,
                output_tokens=10,
                total_tokens=110,
                latency_ms=1.0,
                timestamp=utc_now(),
                status="ok",
                synthetic_origin=True,
            )

        if mode == FixtureBehaviorMode.UNEXPECTED_FIELDS:
            payload = _build_valid_investigation_payload(request)
            payload["unauthorized_extra_field"] = "override_flag"
            return GatewayLLMResponse(
                request_id=request.request_id,
                provider=self.provider_name,
                model=request.model_name,
                provider_response_id=f"fix_{uuid.uuid4().hex[:12]}",
                content=json.dumps(payload),
                structured_response=payload,
                finish_reason="stop",
                input_tokens=140,
                output_tokens=60,
                total_tokens=200,
                latency_ms=1.0,
                timestamp=utc_now(),
                status="ok",
                synthetic_origin=True,
            )

        if mode in {
            FixtureBehaviorMode.UNSUPPORTED_TOOL,
            FixtureBehaviorMode.FORBIDDEN_TOOL_REQUEST,
        }:
            tool_name = (
                "mutate_feature_flag"
                if mode == FixtureBehaviorMode.FORBIDDEN_TOOL_REQUEST
                else "unknown_shell_exec"
            )
            payload = _build_valid_investigation_payload(request)
            return GatewayLLMResponse(
                request_id=request.request_id,
                provider=self.provider_name,
                model=request.model_name,
                provider_response_id=f"fix_{uuid.uuid4().hex[:12]}",
                content=json.dumps(payload),
                structured_response=payload,
                requested_tool_calls=[
                    ToolCallRequest(
                        call_id="call_fix_001",
                        tool_name=tool_name,
                        arguments={"target": "disable_all"},
                    )
                ],
                finish_reason="tool_calls",
                input_tokens=140,
                output_tokens=50,
                total_tokens=190,
                latency_ms=1.0,
                timestamp=utc_now(),
                status="ok",
                synthetic_origin=True,
            )

        payload = (
            self._custom_payload_fn(request)
            if self._custom_payload_fn is not None
            else _build_valid_investigation_payload(request)
        )

        if mode == FixtureBehaviorMode.HALLUCINATED_EVIDENCE:
            payload["evidence_ids"] = [*payload.get("evidence_ids", []), "art_invented_999999"]
            payload["grounded_facts"] = [
                {
                    "claim_id": "clm_hallucinated",
                    "statement": "Test confirmed broad exploitability via fabricated artifact.",
                    "classification": ClaimCategory.OBSERVED.value,
                    "evidence_ids": ["art_invented_999999"],
                    "source_excerpt_ids": [],
                    "limitations": [],
                }
            ]
        elif mode == FixtureBehaviorMode.CONTRADICTORY_CLAIM:
            ev = payload.get("evidence_ids", []) or ["art_repro_0001"]
            payload["grounded_facts"] = [
                {
                    "claim_id": "clm_contra",
                    "statement": "The security test passed cleanly with no vulnerability found.",
                    "classification": ClaimCategory.OBSERVED.value,
                    "evidence_ids": ev[:1],
                    "source_excerpt_ids": [],
                    "limitations": [],
                }
            ]
        elif mode == FixtureBehaviorMode.REPRODUCED_OVERCLAIM:
            ev = payload.get("evidence_ids", []) or ["art_scan_0001"]
            payload["grounded_facts"] = [
                {
                    "claim_id": "clm_overclaim",
                    "statement": "Vulnerability exploitation was reproduced against production.",
                    "classification": ClaimCategory.OBSERVED.value,
                    "evidence_ids": ev[:1],
                    "source_excerpt_ids": [],
                    "limitations": [],
                }
            ]
        elif mode == FixtureBehaviorMode.CVE_EXPLOITED_OVERCLAIM:
            ev = payload.get("evidence_ids", []) or ["art_cve_0001"]
            payload["grounded_facts"] = [
                {
                    "claim_id": "clm_cve_over",
                    "statement": "CVE-2024-9999 was actively reproduced and exploited in runtime.",
                    "classification": ClaimCategory.OBSERVED.value,
                    "evidence_ids": ev[:1],
                    "source_excerpt_ids": [],
                    "limitations": [],
                }
            ]
        elif mode == FixtureBehaviorMode.DEPLOYED_WITHOUT_EVIDENCE:
            ev = payload.get("evidence_ids", []) or ["art_repro_0001"]
            payload["grounded_facts"] = [
                {
                    "claim_id": "clm_dep_over",
                    "statement": (
                        "The source repair has been deployed and the incident is contained."
                    ),
                    "classification": ClaimCategory.OBSERVED.value,
                    "evidence_ids": ev[:1],
                    "source_excerpt_ids": [],
                    "limitations": [],
                }
            ]

        input_tok = None if mode == FixtureBehaviorMode.MISSING_USAGE else 180
        output_tok = None if mode == FixtureBehaviorMode.MISSING_USAGE else 95
        total_tok = None if mode == FixtureBehaviorMode.MISSING_USAGE else 275

        return GatewayLLMResponse(
            request_id=request.request_id,
            provider=self.provider_name,
            model=request.model_name,
            provider_response_id=f"fix_{uuid.uuid4().hex[:12]}",
            content=json.dumps(payload),
            structured_response=payload,
            finish_reason="stop",
            input_tokens=input_tok,
            output_tokens=output_tok,
            total_tokens=total_tok,
            latency_ms=1.5,
            timestamp=utc_now(),
            status="ok",
            synthetic_origin=True,
        )
